def _decrypt_password(enc: str) -> str:
    """XOR + Base64 解密环境变量中的密码"""
    try:
        data = base64.b64decode(enc)
        return bytes(data[i] ^ _KEY[i % len(_KEY)] for i in range(len(data))).decode('utf-8')
    except Exception:
        return enc  # 解密失败则当明文处理（兼容旧版）

